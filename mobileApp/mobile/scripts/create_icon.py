"""Reproducible app identity from vector strokes; no fonts or generated art."""
from pathlib import Path
from math import cos, sin, pi
from PIL import Image, ImageDraw
from PIL.PngImagePlugin import PngInfo
root = Path(__file__).resolve().parents[1] / 'assets/images'
for name, background in [('zinc-icon.png', '#126bc5'), ('zinc-splash.png', (0, 0, 0, 0))]:
    image = Image.new('RGBA', (1024, 1024), background)
    draw = ImageDraw.Draw(image)
    width = 62
    for i in range(8):
        angle = i * pi / 4
        end = (512 + 250 * cos(angle), 512 + 250 * sin(angle))
        draw.line([(512, 512), end], fill='white', width=width)
        x, y = end
        draw.ellipse((x-width/2,y-width/2,x+width/2,y+width/2),fill='white')
    metadata = PngInfo()
    metadata.add_text('Origin', 'ZINC vector icon. Generated by mobile/scripts/create_icon.py using Pillow; eight white radial strokes, no fonts.')
    image.save(root / name, pnginfo=metadata)
